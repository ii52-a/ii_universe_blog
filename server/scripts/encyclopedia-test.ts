import assert from 'node:assert/strict'
import { getDatabase, type DbClient } from '../lib/db'
import { encyclopediaSchemaStatements, getTutorialChapter, getTutorialCourse, listTutorialCourses, searchTutorials } from '../lib/encyclopedia'
import { parseTutorial, seedEncyclopedia } from '../lib/encyclopediaSeed'
import { canManageTutorials } from '../../src/lib/encyclopedia'
import { createTutorialCourse, updateTutorialCourse, deleteTutorialCourse, createTutorialChapter, updateTutorialChapter, deleteTutorialChapter,
  createTutorialSection, updateTutorialSection, deleteTutorialSection, newCourseSchema, updateChapterSchema, reorderTutorials, tutorialOrderSchema } from '../lib/encyclopediaAdmin'

process.env.PGLITE_DIR = 'memory://'
delete process.env.DATABASE_URL
const db = await getDatabase()
try {
  for (const statement of encyclopediaSchemaStatements) await db.exec(statement)
  await db.exec('CREATE TABLE app_meta(key text PRIMARY KEY,value text NOT NULL)')
  const failing: DbClient = { ...db, transaction: run => db.transaction(tx => run({ ...tx,
    async query(text, params) { if (text.startsWith('INSERT INTO tutorial_sections')) throw new Error('Simulated import failure'); return tx.query(text, params) },
  })) }
  await assert.rejects(seedEncyclopedia(failing), /Simulated import failure/)
  assert.equal((await listTutorialCourses(db)).length, 0)
  assert.equal((await db.query('SELECT * FROM app_meta')).rows.length, 0, 'A failed import must roll back the marker and all content')
  await seedEncyclopedia(db)
  const courses = await listTutorialCourses(db)
  assert.deepEqual(courses.map(course => course.slug), ['github', 'html', 'css', 'javascript', 'iiuniverse'])
  const academic = courses.filter(course => course.collection === 'academic')
  assert.equal(academic.reduce((sum, course) => sum + course.chapterCount, 0), 43)
  assert.equal(academic.reduce((sum, course) => sum + course.sectionCount, 0), 159)
  const universe = courses.find(course => course.slug === 'iiuniverse')
  assert.equal(universe?.collection, 'fun')
  assert.equal(universe?.chapterCount, 17)
  assert.equal(universe?.sectionCount, 87)
  for (const course of courses) {
    const detail = await getTutorialCourse(db, course.slug)
    assert.ok(detail && detail.chapters.length === course.chapterCount)
    for (const outline of detail.chapters) {
      const chapter = await getTutorialChapter(db, course.slug, outline.slug)
      assert.ok(chapter && chapter.sections.length === outline.sections.length)
      assert.ok(!('body' in outline), 'The outline must not download all chapter bodies')
      for (const section of chapter.sections) assert.match(section.body, /官方(?:文档|工具)：.*https:\/\//, `${course.slug}/${outline.slug}/${section.slug} needs related official documentation`)
    }
  }
  assert.equal(await getTutorialCourse(db, 'missing'), null)
  assert.equal(await getTutorialChapter(db, 'html', 'missing'), null)
  assert.equal((await searchTutorials(db, "' OR 1=1 --")).length, 0)
  assert.equal((await searchTutorials(db, '')).length, 0)
  assert.ok((await searchTutorials(db, '盒模型')).some(result => result.courseSlug === 'css'))
  await db.query('UPDATE tutorial_sections SET body=$1 WHERE course_slug=$2 AND chapter_slug=$3 AND slug=$4', ['Database-only sentinel', 'html', 'start', 'web'])
  // Model an installed v1 course with both built-in and separately authored content.
  await deleteTutorialCourse(db, 'iiuniverse')
  await db.query('DELETE FROM app_meta WHERE key=$1', ['encyclopedia_iiuniverse_v2'])
  await db.query('INSERT INTO app_meta (key, value) VALUES ($1, $2)', ['encyclopedia_iiuniverse_v1', '1'])
  await createTutorialCourse(db, { slug: 'iiuniverse', title: '既有课程', description: '', category: '全析', color: '#846d52', collection: 'fun' })
  await createTutorialChapter(db, 'iiuniverse', { slug: 'allofstart', title: '引言', body: '原有引言' })
  await createTutorialSection(db, 'iiuniverse', 'allofstart', { slug: 'allofwhy', title: '一切的开始', body: '原有小节' })
  await createTutorialChapter(db, 'iiuniverse', { slug: 'read-the-project', title: '旧章', body: '旧版章导读' })
  await createTutorialSection(db, 'iiuniverse', 'read-the-project', { slug: 'first-map', title: '旧节', body: '旧版正文' })
  await createTutorialSection(db, 'iiuniverse', 'read-the-project', { slug: 'local-notes', title: '附注', body: '后台添加的独立内容' })
  await assert.rejects(seedEncyclopedia(failing), /Simulated import failure/)
  assert.equal((await getTutorialCourse(db, 'iiuniverse'))?.chapterCount, 2)
  assert.equal((await getTutorialChapter(db, 'iiuniverse', 'read-the-project'))?.body, '旧版章导读')
  await seedEncyclopedia(db)
  const upgraded = await getTutorialCourse(db, 'iiuniverse')
  assert.equal(upgraded?.title, '既有课程')
  assert.equal(upgraded?.chapterCount, 18)
  assert.deepEqual(upgraded?.chapters.slice(0, 2).map(chapter => chapter.slug), ['allofstart', 'read-the-project'])
  assert.equal((await getTutorialChapter(db, 'iiuniverse', 'allofstart'))?.sections[0].body, '原有小节')
  const revised = await getTutorialChapter(db, 'iiuniverse', 'read-the-project')
  assert.match(revised?.body ?? '', /读完本章/)
  assert.deepEqual(revised?.sections.slice(0, 2).map(section => section.slug), ['first-map', 'local-notes'])
  assert.match(revised?.sections[0].body ?? '', /浏览器负责/)
  assert.equal(revised?.sections[1].body, '后台添加的独立内容')
  assert.ok((await searchTutorials(db, 'SQLite', 'fun')).some(result => result.sectionSlug === 'database-comparison'))
  await updateTutorialSection(db, 'iiuniverse', 'read-the-project', 'first-map', { body: '版本升级之后的后台编辑' })
  await seedEncyclopedia(db)
  assert.equal((await getTutorialChapter(db, 'iiuniverse', 'read-the-project'))?.sections[0].body, '版本升级之后的后台编辑')
  assert.ok((await searchTutorials(db, 'Zobrist', 'fun')).some(result => result.chapterSlug === 'gomoku-search' && result.sectionSlug === 'transposition-budget'))
  assert.equal((await searchTutorials(db, 'Zobrist', 'academic')).length, 0)
  assert.equal((await getTutorialChapter(db, 'html', 'start'))?.sections[0].body, 'Database-only sentinel', 'Restarting must preserve database edits')
  assert.ok((await searchTutorials(db, 'Database-only sentinel')).some(result => result.courseSlug === 'html'))
  await seedEncyclopedia(db, { refresh: true })
  assert.notEqual((await getTutorialChapter(db, 'html', 'start'))?.sections[0].body, 'Database-only sentinel')
  assert.equal((await getTutorialCourse(db, 'iiuniverse'))?.chapters[0].slug, 'allofstart')
  assert.ok(canManageTutorials({ id: '00000000-0000-4000-8000-000000000002', role: 'admin' }))
  assert.equal(canManageTutorials({ id: '00000000-0000-4000-8000-000000000002', role: 'member' }), false)
  assert.equal(canManageTutorials({ id: 'someone-else', role: 'admin' }), false)
  assert.equal(canManageTutorials(null), false)
  assert.equal(newCourseSchema.safeParse({ slug: 'manage' }).success, false)
  await createTutorialCourse(db, { slug: 'test-course', title: '测试教程', description: '测试', category: '实验', color: '#536485', collection: 'fun' })
  await assert.rejects(createTutorialCourse(db, { slug: 'test-course', title: '重复', description: '', category: '实验', color: '#536485', collection: 'fun' }))
  await createTutorialChapter(db, 'test-course', { slug: 'first', title: '第一章', body: '保留导读' })
  await updateTutorialChapter(db, 'test-course', 'first', updateChapterSchema.parse({ title: '新标题' }))
  assert.equal((await getTutorialChapter(db, 'test-course', 'first'))?.body, '保留导读')
  await createTutorialSection(db, 'test-course', 'first', { slug: 'one', title: '小节', body: 'fun-only-token' })
  await updateTutorialSection(db, 'test-course', 'first', 'one', { title: '已编辑', body: 'fun-only-token updated' })
  assert.equal((await getTutorialChapter(db, 'test-course', 'first'))?.sections[0].title, '已编辑')
  assert.equal((await searchTutorials(db, 'fun-only-token', 'academic')).length, 0)
  assert.equal((await searchTutorials(db, 'fun-only-token', 'fun')).length, 1)
  await createTutorialChapter(db, 'test-course', { slug: 'second', title: '第二章', body: '第二章导读' })
  await createTutorialSection(db, 'test-course', 'second', { slug: 'other', title: '其他章节的小节', body: '不能跨章节移动' })
  await createTutorialSection(db, 'test-course', 'first', { slug: 'another', title: '第二节', body: '第二节正文' })
  const order = { kind: 'sections' as const, course: 'test-course', chapter: 'first', slugs: ['another', 'one'] }
  await reorderTutorials(db, order)
  assert.deepEqual((await getTutorialChapter(db, 'test-course', 'first'))?.sections.map(item => item.slug), ['another', 'one'])
  assert.equal((await getTutorialChapter(db, 'test-course', 'first'))?.sections[1].body, 'fun-only-token updated')
  await assert.rejects(reorderTutorials(db, { ...order, slugs: ['one'] }), /目录已发生变化/)
  await assert.rejects(reorderTutorials(db, { ...order, slugs: ['other', 'one'] }), /目录已发生变化/)
  assert.deepEqual((await getTutorialChapter(db, 'test-course', 'first'))?.sections.map(item => item.slug), ['another', 'one'], 'Rejected stale/cross-chapter orders must roll back')
  assert.equal(tutorialOrderSchema.safeParse({ ...order, slugs: ['one', 'one'] }).success, false)
  await createTutorialSection(db, 'test-course', 'first', { slug: 'appended', title: '追加小节', body: '排在当前章节末尾' })
  assert.deepEqual((await getTutorialChapter(db, 'test-course', 'first'))?.sections.map(item => item.slug), ['another', 'one', 'appended'])
  await reorderTutorials(db, { kind: 'chapters', course: 'test-course', slugs: ['second', 'first'] })
  assert.deepEqual((await getTutorialCourse(db, 'test-course'))?.chapters.map(item => item.slug), ['second', 'first'])
  const courseOrder = (await listTutorialCourses(db)).map(item => item.slug).reverse()
  await reorderTutorials(db, { kind: 'courses', slugs: courseOrder })
  assert.deepEqual((await listTutorialCourses(db)).map(item => item.slug), courseOrder)
  await deleteTutorialChapter(db, 'test-course', 'second')
  await deleteTutorialSection(db, 'test-course', 'first', 'another')
  await deleteTutorialSection(db, 'test-course', 'first', 'appended')
  await updateTutorialCourse(db, 'test-course', { title: '新教程名', description: '', collection: 'academic' })
  assert.equal((await getTutorialCourse(db, 'test-course'))?.collection, 'academic')
  await deleteTutorialSection(db, 'test-course', 'first', 'one')
  assert.equal((await getTutorialChapter(db, 'test-course', 'first'))?.sections.length, 0)
  await createTutorialSection(db, 'test-course', 'first', { slug: 'two', title: '级联小节', body: 'body' })
  await deleteTutorialChapter(db, 'test-course', 'first')
  assert.equal((await db.query('SELECT * FROM tutorial_sections WHERE course_slug=$1', ['test-course'])).rows.length, 0)
  await createTutorialChapter(db, 'test-course', { slug: 'last', title: '最后一章', body: '' })
  await createTutorialSection(db, 'test-course', 'last', { slug: 'last-section', title: '末节', body: 'body' })
  await deleteTutorialCourse(db, 'test-course')
  assert.equal(await getTutorialCourse(db, 'test-course'), null)
  assert.equal((await db.query('SELECT * FROM tutorial_sections WHERE course_slug=$1', ['test-course'])).rows.length, 0)
  await assert.rejects(deleteTutorialCourse(db, 'missing'))
  await assert.rejects(createTutorialChapter(db, 'missing', { slug: 'a', title: 'a', body: '' }))
  const fixture = parseTutorial('## first | First\nIntro\n### section | Section\n````md\n## fake | Fake\n```js\nhello\n```\n````\n## second | Second\n### another | Another\nContent')
  assert.equal(fixture.length, 2)
  assert.match(fixture[0].sections[0].lines.join('\n'), /## fake/)
  console.log('PASS: transactional import, existing-course upgrade, catalog/chapter/search, CRUD, three-level ordering, stale-order rollback, scope isolation and preservation of database edits')
} finally { await db.close?.() }

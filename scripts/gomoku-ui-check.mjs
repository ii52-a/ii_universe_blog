const confirm = () => page.getByRole('button',{name:'确认开局',exact:false}).click()
const screenshot = (name) => page.screenshot({path:`screenshots/current-${name}.png`,fullPage:true})
const a11y = async () => {
  const result = await new AxeBuilder({page}).include('.starboard').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  assert.deepEqual(result.violations.map(v=>({id:v.id, nodes:v.nodes.map(n=>n.target)})),[])
}

